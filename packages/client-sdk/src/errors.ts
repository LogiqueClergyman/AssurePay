export function clientErrorCode(error: unknown): string {
  try {
    const message = error instanceof Error ? error.message : undefined;
    if (message === 'PREVIEW_STALE') return 'CLIENT_PREVIEW_STALE';
    return typeof message === 'string' && CODES.has(message) ? message : 'CLIENT_OPERATION_FAILED';
  } catch { return 'CLIENT_OPERATION_FAILED'; }
}
