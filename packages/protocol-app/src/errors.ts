const CODES = new Set([
  'PROTOCOL_OPERATION_FAILED', 'PROTOCOL_ARGUMENT_INVALID', 'PROTOCOL_AMOUNT_INVALID',
  'PROTOCOL_ID_INVALID', 'PROTOCOL_ADDRESS_INVALID', 'PROTOCOL_ROLE_INVALID', 'PROTOCOL_CONFIG_INVALID',
  'PROTOCOL_ACCOUNT_INVALID', 'PROTOCOL_SIGNER_REQUIRED', 'PROTOCOL_FORBIDDEN', 'PROTOCOL_NOT_FOUND',
  'PROTOCOL_LIMIT', 'PROTOCOL_STATE_UNAVAILABLE', 'PROTOCOL_CONTEXT_MISMATCH', 'PROTOCOL_RPC_UNAVAILABLE',
  'PROTOCOL_REORG', 'PROTOCOL_CURSOR_INVALID', 'PROTOCOL_EXPIRED', 'PROTOCOL_STORAGE_INVALID',
  'PROTOCOL_JOURNAL_INVALID', 'PROTOCOL_JOURNAL_MISSING', 'PROTOCOL_JOURNAL_CHANGED',
  'PROTOCOL_UNRESOLVED', 'PROTOCOL_LOCKED', 'PROTOCOL_SIMULATION_FAILED', 'PROTOCOL_PREVIEW_REQUIRED',
  'PROTOCOL_PREVIEW_EXPIRED', 'PROTOCOL_PREVIEW_STALE', 'PROTOCOL_APPROVAL_REQUIRED',
  'PROTOCOL_GAS_UNAVAILABLE', 'PROTOCOL_NONCE_BUSY', 'PROTOCOL_TX_INVALID', 'PROTOCOL_CLOSED',
  'PROTOCOL_CLOSE_FAILED', 'PROTOCOL_SESSION_REQUIRED', 'PROTOCOL_BOOTSTRAP_INVALID',
  'PROTOCOL_CSRF_REQUIRED', 'PROTOCOL_ORIGIN_INVALID', 'PROTOCOL_HOST_INVALID',
  'PROTOCOL_MEDIA_INVALID', 'PROTOCOL_BODY_TOO_LARGE', 'PROTOCOL_METHOD_INVALID',
]);
export function protocolErrorCode(error: unknown): string {
  try {
    const message = error instanceof Error ? error.message : undefined;
    return typeof message === 'string' && CODES.has(message) ? message : 'PROTOCOL_OPERATION_FAILED';
  } catch { return 'PROTOCOL_OPERATION_FAILED'; }
}
